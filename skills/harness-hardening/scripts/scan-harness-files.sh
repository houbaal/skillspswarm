#!/usr/bin/env bash
# scan-harness-files.sh — Deterministic file-level scan of a coding-agent harness
#
# Reports what's present at the FILE level of a project's harness surface:
# agent instruction files, path-scoped rules, Claude Code hooks, git-level
# hooks, formatters, linters, type checkers, MCP configs, skills/commands
# surface, architectural enforcement hints.
#
# This is a coverage check, nothing more. It tells you what is ON DISK;
# it does NOT judge whether any of it is good. Pair the output with the
# inferential criteria in ../references/ (CLAUDE.md hand-craft quality,
# P6 remediation-aware error messages, P1 path-scoping usage, etc.) to
# get an actual audit.
#
# Usage: scan-harness-files.sh [target-dir]
#        Defaults to the current working directory.
#
# Works against both regular project repos (where harness files sit under
# `.claude/`) and `~/.claude/` itself (where the `.claude/` prefix is
# already there). Every `.claude/X` check falls back to `X` when the
# prefixed path is missing — that way one script handles both shapes.
#
# Why this script exists (and why its name is what it is):
# the Phase 1 inventory is partly deterministic (does a file exist?)
# and partly inferential (is it any good?). The deterministic slice is
# the boring-but-repetitive part that benefits most from automation.
# The script is named `scan-harness-files` rather than `inventory-harness`
# because "inventory" overclaims — only the file layer is covered here,
# not hooks semantics, not tool call patterns, not context quality.

set -u  # no -e on purpose: grep -q and pipes misbehave under bash 3.2 + set -e

TARGET="${1:-.}"
if [ ! -d "$TARGET" ]; then
  echo "Error: '$TARGET' is not a directory" >&2
  exit 1
fi
TARGET="$(cd "$TARGET" && pwd)"

section() { printf '\n## %s\n\n' "$1"; }
found()   { printf -- '- %s\n' "$1"; }
missing() { printf -- '- _missing_: %s\n' "$1"; }

linecount() {
  [ -f "$1" ] || { echo 0; return; }
  wc -l < "$1" | tr -d ' '
}

# Resolve a path that may live at .claude/X (normal project) or at X directly
# (when scanning ~/.claude itself). Echoes the first existing path, nothing
# otherwise.
resolve_claude_path() {
  local rel="$1"
  if [ -e "$TARGET/.claude/$rel" ]; then
    echo "$TARGET/.claude/$rel"
  elif [ -e "$TARGET/$rel" ]; then
    echo "$TARGET/$rel"
  fi
}

has_any_of() {
  # First arg = label, rest = relative paths to test under $TARGET
  local label="$1"; shift
  local f
  for f in "$@"; do
    if [ -f "$TARGET/$f" ]; then
      found "$label: \`$f\`"
      return 0
    fi
  done
  return 1
}

has_toml_section() {
  local label="$1" tag="$2" file="$3"
  [ -f "$TARGET/$file" ] || return 1
  if grep -q "^\\[$tag\\]" "$TARGET/$file" 2>/dev/null; then
    found "$label (in \`$file\`)"
    return 0
  fi
  return 1
}

printf '# Harness file scan: %s\n' "$TARGET"
cat <<'EOF'

_Generated by `scan-harness-files.sh`. Deterministic file-level scan only —
no quality judgement. Pair with the inferential principles in `../references/`
for the full audit (quality of CLAUDE.md, remediation-awareness of error
messages, hand-crafted vs auto-generated, etc.)._
EOF

# --- 1. Agent instruction files ---
section "Agent instruction files (root-level)"
any_found=0
for f in CLAUDE.md AGENTS.md .cursorrules .github/copilot-instructions.md; do
  if [ -f "$TARGET/$f" ]; then
    found "\`$f\` ($(linecount "$TARGET/$f") lines)"
    any_found=1
  fi
done
[ "$any_found" -eq 0 ] && missing "no root-level agent instruction files found"

section "Subdirectory \`CLAUDE.md\` files (path-scoped by directory)"
subfiles="$(find "$TARGET" -type f -name 'CLAUDE.md' 2>/dev/null | grep -v "^$TARGET/CLAUDE.md$" | head -30 || true)"
if [ -n "$subfiles" ]; then
  echo "$subfiles" | while IFS= read -r f; do
    [ -z "$f" ] && continue
    rel="${f#$TARGET/}"
    printf -- '- `%s` (%s lines)\n' "$rel" "$(linecount "$f")"
  done
else
  missing "no subdirectory CLAUDE.md files"
fi

# --- 2. Path-scoped rules directory ---
section "\`rules/\` (path-scoped instructions, most precise layer)"
RULES_DIR="$(resolve_claude_path rules)"
if [ -n "$RULES_DIR" ] && [ -d "$RULES_DIR" ]; then
  rule_files="$(find "$RULES_DIR" -type f -name '*.md' 2>/dev/null)"
  if [ -n "$rule_files" ]; then
    found "scanning \`${RULES_DIR#$TARGET/}/\`"
    echo "$rule_files" | while IFS= read -r f; do
      [ -z "$f" ] && continue
      rel="${f#$TARGET/}"
      if head -20 "$f" 2>/dev/null | grep -q '^paths:'; then
        printf -- '    - `%s` — **path-scoped** (has `paths:` frontmatter)\n' "$rel"
      else
        printf -- '    - `%s` — unconditional (no `paths:` frontmatter)\n' "$rel"
      fi
    done
  else
    missing "rules directory exists but is empty"
  fi
else
  missing "no \`rules/\` or \`.claude/rules/\` directory"
fi

# --- 3. Claude Code hooks ---
section "Claude Code hooks"
hooks_found=0
for prefix in ".claude/" ""; do
  for fname in settings.json settings.local.json; do
    f="$TARGET/${prefix}${fname}"
    # Resolve symlinks for counting purposes but still check existence as-is
    if [ -f "$f" ] || [ -L "$f" ]; then
      hook_list=""
      for hook in PreToolUse PostToolUse UserPromptSubmit Stop SubagentStop SessionStart InstructionsLoaded; do
        if grep -q "\"$hook\"" "$f" 2>/dev/null; then
          hook_list="$hook_list $hook"
        fi
      done
      if [ -n "$hook_list" ]; then
        found "\`${prefix}${fname}\` — hook types:$hook_list"
      else
        found "\`${prefix}${fname}\` — no hooks configured"
      fi
      hooks_found=1
    fi
  done
done
[ "$hooks_found" -eq 0 ] && missing "no \`settings*.json\` found"

# --- 4. Git-level hooks ---
section "Git-level hooks (pre-commit, pre-push)"
git_hooks_found=0
[ -f "$TARGET/.pre-commit-config.yaml" ] && { found "\`.pre-commit-config.yaml\` (pre-commit framework)"; git_hooks_found=1; }
[ -f "$TARGET/.husky/pre-commit" ] && { found "\`.husky/pre-commit\` (husky)"; git_hooks_found=1; }
[ -f "$TARGET/.husky/pre-push" ] && { found "\`.husky/pre-push\` (husky)"; git_hooks_found=1; }
[ -f "$TARGET/lefthook.yml" ] && { found "\`lefthook.yml\`"; git_hooks_found=1; }
[ -f "$TARGET/lefthook.yaml" ] && { found "\`lefthook.yaml\`"; git_hooks_found=1; }
if [ -d "$TARGET/.git/hooks" ]; then
  custom="$(find "$TARGET/.git/hooks" -type f ! -name '*.sample' 2>/dev/null | wc -l | tr -d ' ')"
  if [ "$custom" -gt 0 ]; then
    found "\`.git/hooks/\` — $custom custom hook(s), raw git layer (often bypassable with \`--no-verify\`)"
    git_hooks_found=1
  fi
fi
[ "$git_hooks_found" -eq 0 ] && missing "no git-level hooks detected"

# --- 5. Formatters ---
section "Formatters"
f_found=0
has_any_of "Prettier" .prettierrc .prettierrc.json .prettierrc.yml .prettierrc.yaml prettier.config.js && f_found=1
has_toml_section "Black" "tool.black" "pyproject.toml" && f_found=1
has_any_of "rustfmt" rustfmt.toml .rustfmt.toml && f_found=1
has_any_of ".editorconfig" .editorconfig && f_found=1
[ -f "$TARGET/go.mod" ] && { found "Go module detected (gofmt implied)"; f_found=1; }
[ "$f_found" -eq 0 ] && missing "no formatter config detected"

# --- 6. Linters ---
section "Linters"
l_found=0
has_any_of "ESLint" .eslintrc .eslintrc.js .eslintrc.json .eslintrc.yml eslint.config.js eslint.config.mjs && l_found=1
has_toml_section "Ruff" "tool.ruff" "pyproject.toml" && l_found=1
has_any_of "golangci-lint" .golangci.yml .golangci.yaml .golangci.toml && l_found=1
has_any_of "Clippy" clippy.toml .clippy.toml && l_found=1
[ "$l_found" -eq 0 ] && missing "no linter config detected"

# --- 7. Type checkers ---
section "Type checkers"
t_found=0
if [ -f "$TARGET/tsconfig.json" ]; then
  if grep -q '"strict"[[:space:]]*:[[:space:]]*true' "$TARGET/tsconfig.json" 2>/dev/null; then
    found "\`tsconfig.json\` (**strict mode ON**)"
  else
    found "\`tsconfig.json\` (strict mode NOT explicitly on — weak signal)"
  fi
  t_found=1
fi
has_any_of "mypy" mypy.ini && t_found=1
has_toml_section "mypy" "tool.mypy" "pyproject.toml" && t_found=1
has_any_of "Pyright" pyrightconfig.json && t_found=1
[ "$t_found" -eq 0 ] && missing "no type checker config detected"

# --- 8. MCP configurations ---
section "MCP configurations"
mcp_found=0
[ -f "$TARGET/.mcp.json" ] && { found "\`.mcp.json\` (project-level)"; mcp_found=1; }
[ -f "$TARGET/.claude/mcp.json" ] && { found "\`.claude/mcp.json\`"; mcp_found=1; }
[ -f "$TARGET/mcp.json" ] && { found "\`mcp.json\`"; mcp_found=1; }
[ "$mcp_found" -eq 0 ] && missing "no MCP configuration (which is often the right answer — see P2)"

# --- 9. Skills / commands / agents surface ---
section "Skills, commands, agents surface"
any_ca=0
for kind in skills commands agents; do
  dir="$(resolve_claude_path "$kind")"
  if [ -n "$dir" ] && [ -d "$dir" ]; then
    rel="${dir#$TARGET/}"
    case "$kind" in
      skills)
        n="$(find "$dir" -maxdepth 3 -name 'SKILL.md' 2>/dev/null | wc -l | tr -d ' ')"
        found "\`$rel/\` — $n SKILL.md files"
        ;;
      commands)
        n="$(find "$dir" -type f -name '*.md' 2>/dev/null | wc -l | tr -d ' ')"
        found "\`$rel/\` — $n command files"
        ;;
      agents)
        n="$(find "$dir" -type f -name '*.md' 2>/dev/null | wc -l | tr -d ' ')"
        found "\`$rel/\` — $n agent files"
        ;;
    esac
    any_ca=1
  fi
done
[ "$any_ca" -eq 0 ] && missing "no \`skills|commands|agents\` present"

# --- 10. Architectural enforcement hints ---
section "Architectural enforcement hints"
a_found=0
has_any_of "dependency-cruiser" .dependency-cruiser.js .dependency-cruiser.json .dependency-cruiser.cjs && a_found=1
[ "$a_found" -eq 0 ] && missing "no structural dependency tool detected (doesn't rule out fitness functions embedded in test suites)"

cat <<'EOF'

---

_End of deterministic scan. What this script does NOT cover:_

1. _**Quality of agent instruction files** — is CLAUDE.md hand-crafted, is it mostly inferable content? See P1 in `../references/principles-feedforward.md`._
2. _**Hook semantics** — the hook types are listed, but are they TDD guards, destructive-command blocklists, token budgets, pipeline-red injectors? See P5 in `../references/principles-sensors.md`._
3. _**Error message quality** — do lint/test messages include remediation? See P6._
4. _**Test verifiability in-session** — can the agent actually run the suite without a long setup? See P3._
5. _**Real-system verification** — is anything wired to a running app or observability? See P12._

_Next step: read `../references/meta-principles.md`, then score each dimension 0-4 using `../references/maturity-scorecard.md`._
EOF
